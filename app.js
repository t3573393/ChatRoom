// Socket.io 连接处理
// 当有新的客户端连接到服务器时触发
ios.on('connection', function(socket){
	logger.info('Connection', '新客户端连接: ' + socket.id);

	// 用户加入房间事件处理
	// 处理新用户加入房间请求，包括用户名冲突检测和房间权限设置
	socket.on('new user', function(data, callback){
		var originalUsername = data.username;
		var finalUsername = originalUsername;
		var suffix = 1;
		var maxAttempts = 10;
		
		// 查找可用的用户名（添加数字后缀）
		while (userManager.isUserOnline(finalUsername) && suffix <= maxAttempts) {
			finalUsername = originalUsername + suffix;
			suffix++;
		}
		
		if (suffix > maxAttempts) {
			// 所有名字都被占用
			callback({success: false, error: '用户名已满，请稍后再试'});
			return;
		}
		
		// 用户名可用
		socket.username = finalUsername;
		socket.userAvatar = data.userAvatar;
		socket.roomCode = data.roomCode;
		socket.isWritting = false;
		socket.activo = true;
		userManager.addUser(socket);
		
		// 将socket加入房间，这样才能收到房间内的广播消息
		socket.join(data.roomCode);
		
		var isCreator = roomManager.addRoomCreator(data.roomCode, finalUsername);
		socket.isRoomCreator = isCreator;
		
		logger.info('Auth', '用户 ' + finalUsername + ' 加入房间 ' + data.roomCode + ' (创建者:' + isCreator + ')' + (suffix > 1 ? ' (原名:' + originalUsername + ')' : ''));
		
		// 返回成功，并告诉前端最终使用的用户名
		if (suffix > 1) {
			callback({success: true, username: finalUsername, autoGenerated: true});
		} else {
			callback({success: true});
		}
	});

	socket.on('kick-user', function(data, callback) {
		if (!socket.username || !socket.roomCode) {
			callback({success: false, message: '参数错误'});
			return;
		}
		
		if (!roomManager.isRoomCreator(socket.roomCode, socket.username)) {
			callback({success: false, message: '您没有权限执行此操作'});
			return;
		}
		
		if (data.targetUsername == socket.username) {
			callback({success: false, message: '不能踢出自己'});
			return;
		}
		
		var success = roomManager.kickUser(socket.roomCode, data.targetUsername);
		
		if (success) {
			var targetSocket = userManager.getUser(data.targetUsername);
			if (targetSocket) {
				targetSocket.emit('you-have-been-kicked', {
					roomCode: socket.roomCode,
					message: '您已被管理员踢出房间'
				});
				
				targetSocket.disconnect(true);
				
				userManager.removeUser(data.targetUsername);
			}
			
			ios.sockets.in(socket.roomCode).emit('user-kicked', {
				kickedUsername: data.targetUsername,
				operator: socket.username
			});
			
			logger.info('Admin', '用户 ' + socket.username + ' 踢出 ' + data.targetUsername + ' 从房间 ' + socket.roomCode);
			
			callback({success: true});
		} else {
			callback({success: false, message: '操作失败'});
		}
	});

	socket.on('mute-user', function(data, callback) {
		if (!socket.username || !socket.roomCode) {
			callback({success: false, message: '参数错误'});
			return;
		}
		
		if (!roomManager.isRoomCreator(socket.roomCode, socket.username)) {
			callback({success: false, message: '您没有权限执行此操作'});
			return;
		}
		
		if (data.targetUsername == socket.username) {
			callback({success: false, message: '不能禁言自己'});
			return;
		}
		
		var success = roomManager.muteUser(socket.roomCode, data.targetUsername);
		
		if (success) {
			ios.sockets.in(socket.roomCode).emit('user-muted', {
				mutedUsername: data.targetUsername,
				operator: socket.username
			});
			
			logger.info('Admin', '用户 ' + socket.username + ' 禁言 ' + data.targetUsername + ' 在房间 ' + socket.roomCode);
			
			callback({success: true});
		} else {
			callback({success: false, message: '操作失败'});
		}
	});

	socket.on('unmute-user', function(data, callback) {
		if (!socket.username || !socket.roomCode) {
			callback({success: false, message: '参数错误'});
			return;
		}
		
		if (!roomManager.isRoomCreator(socket.roomCode, socket.username)) {
			callback({success: false, message: '您没有权限执行此操作'});
			return;
		}
		
		var success = roomManager.unmuteUser(socket.roomCode, data.targetUsername);
		
		if (success) {
			ios.sockets.in(socket.roomCode).emit('user-unmuted', {
				unmutedUsername: data.targetUsername,
				operator: socket.username
			});
			
			logger.info('Admin', '用户 ' + socket.username + ' 解禁 ' + data.targetUsername + ' 在房间 ' + socket.roomCode);
			
			callback({success: true});
		} else {
			callback({success: false, message: '操作失败'});
		}
	});

	socket.on('user-activo', function(data, callback){
		if(!userManager.isUserOnline(data.username))
		{
			callback({success:false});
		}else{
			callback({success:true});
			userManager.updateUserStatus(data.username, 'activo', true);
			ios.sockets.emit('online-members', userManager.getAllUsers());
		}
	});

	socket.on('user-inactivo', function(data, callback){
		if(!userManager.isUserOnline(data.username))
		{
			callback({success:false});
		}else{
			callback({success:true});
			userManager.updateUserStatus(data.username, 'activo', false);
			ios.sockets.emit('online-members', userManager.getAllUsers());
		}
	});

	socket.on('user-writting', function(data, callback){
		if(!userManager.isUserOnline(data.username))
		{
			callback({success:false});
		}else{
			callback({success:true});
			userManager.updateUserStatus(data.username, 'isWritting', true);
			ios.sockets.emit('online-members', userManager.getAllUsers());
		}
	});


	socket.on('user-stop-writting', function(data, callback){
		if(!userManager.isUserOnline(data.username))
		{
			callback({success:false});
		}else{
			callback({success:true});
			userManager.updateUserStatus(data.username, 'isWritting', false);
			ios.sockets.emit('online-members', userManager.getAllUsers());
		}
	});

	// sending online members list
	socket.on('get-online-members', function(data){
		ios.sockets.emit('online-members', userManager.getAllUsers());		
	});

	// 消息发送事件处理
	// 处理客户端发送的消息，支持文本、图片、表情、代码块和阅后即焚等多种消息类型
	socket.on('send-message', function(data, callback){
		if (!socket.username || !socket.roomCode) {
			callback({success: false, message: '参数错误'});
			return;
		}
		
		// 权限验证：检查用户是否被禁言
		if (roomManager.isMuted(socket.roomCode, socket.username)) {
			callback({success: false, message: '您已被管理员禁言，无法发送消息'});
			return;
		}
		
		// 敏感词过滤：检测消息内容是否包含敏感词
		var filterResult = roomManager.filterSensitiveWords(data.msg);
		if (filterResult.contains) {
			logger.warn('Security', '检测到敏感词消息: 用户 ' + socket.username + ' 在房间 ' + socket.roomCode);
			callback({success: false, message: '消息包含敏感词，请修改后重试'});
			return;
		}
		
		if (userManager.isUserOnline(data.username)) {
			if(data.hasMsg){
				logger.info('Message', '用户 ' + data.username + ' 在房间 ' + data.roomCode + ' 发送消息: ' + (data.msg ? data.msg.substring(0, 50) : 'null'));
				
				// 处理阅后即焚消息的参数
				var isBurnAfterReading = data.isBurnAfterReading ? 1 : 0;
				var burnDuration = data.burnDuration || 10; // 默认10秒有效期
				
				// 判断消息类型：图片、表情、GIF或文本
				var messageType = data.isImageMSG ? 'image' : data.isMeme ? 'meme' : data.isGif ? 'gif' : 'text';
				var fileInfo = null; // 文本消息没有文件信息
				
				// 将消息保存到数据库，使用 Promise 链确保 ID 一致
				db.saveMessageWithBurn(
					data.roomCode,         // 房间代码
					data.username,         // 发送者用户名
					data.userAvatar,       // 发送者头像
					messageType,           // 消息类型
					data.msg,              // 消息内容
					fileInfo,              // 文件信息（文本消息为null）
					data.isBurnAfterReading, // 是否阅后即焚
					data.burnDuration      // 阅后即焚有效期
				).then(function(messageId) {
					// 消息保存成功，使用数据库返回的真实 ID
					console.log('消息已保存，ID:', messageId);
					
					db.markMessageDelivered(messageId).then(function() {
						ios.sockets.in(data.roomCode).emit('message-delivered', {
							messageId: messageId,
							roomCode: data.roomCode
						});
					}).catch(function(err) {
						logger.error('[Socket-MessageStatus] 标记消息送达失败:', err);
					});
					
					// 根据消息类型广播给客户端
					if (isBurnAfterReading) {
						// 处理阅后即焚消息：只广播给特定房间的用户
						ios.to(data.roomCode).emit('new burn message', {
							username: data.username,
							userAvatar: data.userAvatar,
							msg: data.msg,
							msgTime: data.msgTime,
							isBurnAfterReading: true,
							burnDuration: burnDuration,
							messageId: messageId,
							roomCode: data.roomCode
						});
					} else {
						// 处理普通消息：构建完整的消息对象
						var messageData = {
							username: data.username,         // 发送者用户名
							userAvatar: data.userAvatar,     // 发送者头像
							msg: data.msg,                  // 消息内容
							msgTime: data.msgTime,           // 发送时间
							isImageMSG: data.isImageMSG,     // 是否为图片消息
							isMeme: data.isMeme,             // 是否为表情消息
							isGif: data.isGif,               // 是否为GIF消息
							roomCode: data.roomCode,         // 房间代码
							hasMsg: data.hasMsg,             // 是否包含文本内容
							hasFile: data.hasFile,           // 是否包含文件
							mentions: data.mentions,         // @提到的用户
							replyTo: data.replyTo,           // 回复的消息ID
							messageId: messageId             // 消息唯一ID
						};
						// 广播普通消息给所有客户端
						ios.sockets.emit('new message', messageData);
					}
				}).catch(function(err) {
					// 消息保存失败
					console.error('保存消息失败:', err);
				});
				
				callback({success: true});
			}else if(data.hasFile){
				// 处理文件消息：根据文件类型进行不同处理
				var messageType = data.istype; // image, music, PDF
				var fileInfo = JSON.stringify({
					filename: data.filename,
					serverfilename: data.serverfilename,
					size: data.size,
					type: data.istype
				});

				// 保存文件消息到数据库
				db.saveMessage(
					data.roomCode,
					data.username,
					data.userAvatar,
					messageType,
					data.msg || '[文件消息]',
					fileInfo
				).then(function(messageId) {
					console.log('文件消息已保存，ID:', messageId);
					data.messageId = messageId;

					// 根据文件类型发送不同的事件
					if(data.istype == "image"){
						// 图片文件：发送图片消息事件
						ios.sockets.emit('new message image', data);
						callback({success:true, messageId: messageId});
					} else if(data.istype == "music"){
						// 音频文件：发送音频消息事件
						ios.sockets.emit('new message music', data);
						callback({success:true, messageId: messageId});
					} else if(data.istype == "PDF"){
						// PDF文件：发送PDF消息事件
						ios.sockets.emit('new message PDF', data);
						callback({success:true, messageId: messageId});
					}
				}).catch(function(err) {
					console.error('保存文件消息失败:', err);
					callback({success: false, message: '保存消息失败'});
				});
			}else{
				callback({ success:false});
			}
		}		
	});

	socket.on('edit-message', function(data, callback) {
		if (!socket.username || !socket.roomCode) {
			callback({success: false, message: '参数错误'});
			return;
		}

		var messageId = parseInt(data.messageId);
		var newContent = data.newContent;
		var roomCode = socket.roomCode;
		var username = socket.username;

		if (!messageId || !newContent) {
			callback({success: false, message: '参数不完整'});
			return;
		}

		var timeLimit = 5 * 60 * 1000;

		db.getEditableMessage(messageId, username, timeLimit).then(function(result) {
			if (!result) {
				callback({success: false, message: '消息不存在'});
				return Promise.reject(new Error('not found'));
			}

			if (!result.editable) {
				callback({success: false, message: '消息已超过5分钟编辑时限'});
				return Promise.reject(new Error('expired'));
			}

			return db.saveEditHistory(messageId, result.message.message_content);
		}).then(function() {
			return db.editMessage(messageId, newContent);
		}).then(function(updated) {
			if (updated) {
				ios.sockets.in(roomCode).emit('message-edited', {
					messageId: messageId,
					newContent: newContent,
					editor: username
				});

				logger.info('[Socket-Edit] 用户 ' + username + ' 编辑了消息 ' + messageId);
				callback({success: true});
			} else {
				callback({success: false, message: '编辑失败'});
			}
		}).catch(function(err) {
			if (err.message !== 'not found' && err.message !== 'expired') {
				logger.error('[Socket-Edit] 编辑消息失败:', err);
				callback({success: false, message: '编辑失败'});
			}
		});
	});

	socket.on('recall-message', function(data, callback) {
		if (!socket.username || !socket.roomCode) {
			callback({success: false, message: '参数错误'});
			return;
		}

		var messageId = parseInt(data.messageId);
		var roomCode = socket.roomCode;
		var username = socket.username;

		if (!messageId) {
			callback({success: false, message: '消息ID不能为空'});
			return;
		}

		db.recallMessage(messageId, username).then(function(recalled) {
			if (recalled) {
				ios.sockets.in(roomCode).emit('message-recalled', {
					messageId: messageId,
					recaller: username
				});

				logger.info('[Socket-Recall] 用户 ' + username + ' 撤回了消息 ' + messageId);
				callback({success: true});
			} else {
				callback({success: false, message: '消息不存在或已被撤回'});
			}
		}).catch(function(err) {
			logger.error('[Socket-Recall] 撤回消息失败:', err);
			callback({success: false, message: '撤回失败'});
		});
	});

	socket.on('mark-messages-read', function(data, callback) {
		if (!socket.username || !socket.roomCode) {
			if (callback) callback({success: false, message: '参数错误'});
			return;
		}

		var roomCode = socket.roomCode;
		var username = socket.username;

		db.markMessagesRead(roomCode, username).then(function(count) {
			ios.sockets.in(roomCode).emit('message-read', {
				reader: username,
				roomCode: roomCode,
				count: count
			});

			logger.info('[Socket-MessageStatus] 用户 ' + username + ' 查看了房间 ' + roomCode + ' 的消息');
			if (callback) callback({success: true, count: count});
		}).catch(function(err) {
			logger.error('[Socket-MessageStatus] 批量标记已读失败:', err);
			if (callback) callback({success: false, message: '标记已读失败'});
		});
	});

	socket.on('view-message', function(data, callback) {
		if (!socket.username || !socket.roomCode) {
			if (callback) callback({success: false, message: '参数错误'});
			return;
		}

		var messageId = parseInt(data.messageId);
		var roomCode = socket.roomCode;
		var username = socket.username;

		if (!messageId) {
			if (callback) callback({success: false, message: '消息ID不能为空'});
			return;
		}

		db.markMessageRead(messageId, username).then(function() {
			ios.sockets.in(roomCode).emit('message-read', {
				messageId: messageId,
				reader: username,
				roomCode: roomCode
			});

			logger.info('[Socket-MessageStatus] 用户 ' + username + ' 查看了消息 ' + messageId);
			if (callback) callback({success: true});
		}).catch(function(err) {
			logger.error('[Socket-MessageStatus] 标记消息已读失败:', err);
			if (callback) callback({success: false, message: '标记已读失败'});
		});
	});
	socket.on('remove-meme', function(data, callback){
		if (userManager.isUserOnline(data.username)) {
				ios.sockets.emit('remove meme', data);
				callback({success:true});
		}		
	});
	socket.on('send-meme', function(data, callback){
		if (userManager.isUserOnline(data.username)) {
				ios.sockets.emit('new meme', data);
				callback({success:true});
		}		
	});
	
	// disconnect user handling 
	socket.on('disconnect', function () {	
		if (socket.username && socket.roomCode) {
			roomManager.removeRoomMember(socket.roomCode, socket.username);
		}
		userManager.removeUser(socket.username);
		ios.sockets.emit('online-members', userManager.getAllUsers());            	
   	});
});

