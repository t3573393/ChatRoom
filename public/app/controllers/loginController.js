angular.module('Controllers',[])
.directive('focusMe', function($timeout) {	// Custom directive for focus
    return {
        link: function(scope, element, attrs) {
          scope.$watch(attrs.focusMe, function(value) {
            if(value === true) { 
              $timeout(function() {
                element[0].focus();
                scope[attrs.focusMe] = false;
              });
            }
          });
        }
    };
})
.controller('loginCtrl', function ($scope, $location, $rootScope, $socket){		// Login Controller
	// Varialbles Initialization.
	$scope.isErrorReq = false;
	$scope.isErrorNick = false;
	$scope.username = "";
	
	// 预设头像列表
	$scope.presetAvatars = [
		'app/css/dist/img/Avatar1.jpg',
		'app/css/dist/img/Avatar2.jpg',
		'app/css/dist/img/Avatar3.jpg',
		'app/css/dist/img/Avatar4.jpg',
		'app/css/dist/img/Avatar5.jpg',
		'app/css/dist/img/Avatar6.jpg',
		'app/css/dist/img/Avatar7.jpg',
		'app/css/dist/img/Avatar8.jpg'
	];
	
	// 头像持久化：尝试从localStorage加载上次使用的头像
	var savedAvatar = localStorage.getItem('userAvatar');
	if (savedAvatar) {
		$scope.userAvatar = savedAvatar;
	} else {
		$scope.userAvatar = $scope.presetAvatars[0]; // 默认使用第一个预设头像
	}

	// redirection if user logged in.
	if($rootScope.loggedIn){
		$location.path('/v1/ChatRoom');
	}

	// Functions for controlling behaviour.
	$scope.redirect = function(){
		if ($scope.username.length <= 20) {
			if($scope.username){
				$socket.emit('new user',{username : $scope.username, userAvatar : $scope.userAvatar, roomCode: $scope.roomCode},function(data){
					if(data.success == true){	// if nickname doesn't exists
						// 检查是否自动生成了用户名（重复用户名添加后缀）
						var displayUsername = data.username || $scope.username;
						$rootScope.username = displayUsername;
						$rootScope.userAvatar = $scope.userAvatar;
						$rootScope.roomCode = $scope.roomCode;
						$rootScope.loggedIn = true;
						
						// 保存头像到localStorage
						localStorage.setItem('userAvatar', $scope.userAvatar);
						
						// 如果用户名被自动修改，显示提示
						if (data.autoGenerated && data.username) {
							$scope.showAutoGeneratedNotice(displayUsername);
						}
						
						$location.path('/v1/ChatRoom');					
					}else{		// if nickname exists
						$scope.errMsg = data.error || "用户名已满，请稍后再试";
						$scope.isErrorNick = true;
						$scope.isErrorReq = true;
						$scope.printErr($scope.errMsg);	
					}			
				});
			}else{		// blanck nickname 
				$scope.errMsg = "Enter a nickname.";
				$scope.isErrorReq = true;
				$scope.printErr($scope.errMsg);
			}
		}else{		// nickname greater than limit
			$scope.errMsg = "Nickname exceed 20 charachters.";
			$scope.isErrorNick = true;
			$scope.isErrorReq = true;
			$scope.printErr($scope.errMsg);
		}
	}
	
	// 显示用户名自动生成提示
	$scope.showAutoGeneratedNotice = function(newUsername) {
		alert('用户名 "' + $scope.username + '" 已被使用，您的新用户名是 "' + newUsername + '"');
	}

	$scope.printErr = function(msg){	// popup for error message
		var html = '<p id="alert">'+ msg +'</p>';
		if ($( ".chat-box" ).has( "p" ).length < 1) {
			$(html).hide().prependTo(".chat-box").fadeIn(1500);
			$('#alert').delay(1000).fadeOut('slow', function(){
				$('#alert').remove();
			});
		};
	}
	$scope.changeAvatar = function(avatar){		// selecting different avatar
		$scope.userAvatar = avatar;
		// 保存到localStorage
		localStorage.setItem('userAvatar', avatar);
	}
	$scope.updateImageArray = function(image) { 
		if (image && image.compressed && image.compressed.dataURL) {
			$scope.userAvatar = image.compressed.dataURL;
			// 保存自定义头像到localStorage
			localStorage.setItem('userAvatar', image.compressed.dataURL);
		}
	}
	
	// 清除保存的头像
	$scope.clearSavedAvatar = function() {
		localStorage.removeItem('userAvatar');
		$scope.userAvatar = $scope.presetAvatars[0];
	}
})
